// ═══════════════════════════════════════════════════════════
// routes/ai.ts — POST /api/ai/ideas
// Privacy-first routing: validation, idempotency, Gemini integration,
// deterministic demo fallback, safe error responses.
// ═══════════════════════════════════════════════════════════

import { Router, Request, Response, NextFunction } from 'express'
import { config, isDev } from '../config'
import { IdeaRequestSchema } from '../lib/validate'
import { generateIdeas } from '../lib/gemini'
import { getDemoIdeas } from '../lib/demo'
import type { IdeasApiResponse } from '../lib/validate'

const router = Router()

// In-memory idempotency cache: key → expiry timestamp (bounded to prevent heap exhaustion)
const idempotencyCache = new Map<string, number>()
const IDEMPOTENCY_TTL_MS = 30_000
const MAX_IDEMPOTENCY_ENTRIES = 1_000

function cleanIdempotencyCache() {
  const now = Date.now()
  for (const [key, expiry] of idempotencyCache) {
    if (now > expiry) idempotencyCache.delete(key)
  }
}

function recordIdempotencyKey(key: string, ttlMs = IDEMPOTENCY_TTL_MS) {
  if (idempotencyCache.size >= MAX_IDEMPOTENCY_ENTRIES) {
    cleanIdempotencyCache()
    // If still at capacity, evict oldest entry
    if (idempotencyCache.size >= MAX_IDEMPOTENCY_ENTRIES) {
      const oldest = idempotencyCache.keys().next().value
      if (oldest) idempotencyCache.delete(oldest)
    }
  }
  idempotencyCache.set(key, Date.now() + ttlMs)
}

const DISCLAIMER =
  'These suggestions are generated by AI or curated demo inspiration. ' +
  'All costs are rough estimates — verify with actual vendors before committing.'

router.post('/ideas', async (req: Request, res: Response, next: NextFunction) => {
  try {
    // ── 1. Validate request ───────────────────────────────
    const parsed = IdeaRequestSchema.safeParse(req.body)
    if (!parsed.success) {
      const detail = parsed.error.issues.map((i) => `${i.path.join('.')}: ${i.message}`).join('; ')
      res.status(400).json({ error: 'Invalid request parameters.', ...(isDev && { detail }) })
      return
    }
    const data = parsed.data

    // ── 2. Idempotency check ──────────────────────────────
    if (data.idempotencyKey) {
      cleanIdempotencyCache()
      if (idempotencyCache.has(data.idempotencyKey)) {
        res.status(429).json({ error: 'Duplicate request detected. Please wait before retrying.' })
        return
      }
      recordIdempotencyKey(data.idempotencyKey)
    }

    // ── 3. Decide: Gemini or demo ─────────────────────────
    const hasKey = Boolean(config.GEMINI_API_KEY && config.GEMINI_API_KEY.trim().length > 0)
    if (!hasKey) {
      const ideas = getDemoIdeas(data)
      const response: IdeasApiResponse = { ideas, source: 'demo', disclaimer: DISCLAIMER }
      res.json(response)
      return
    }

    // ── 4. Call Gemini with retry policy ──────────────────
    const result = await generateIdeas(data)

    if (result.ok) {
      const response: IdeasApiResponse = { ideas: result.ideas, source: 'gemini', disclaimer: DISCLAIMER }
      res.json(response)
      return
    }

    // ── 5. Handle failure cases safely ───────────────────
    switch (result.reason) {
      case 'rate-limited': {
        res.setHeader('Retry-After', String(result.retryAfterSecs ?? 60))
        res.status(503).json({ error: 'AI service is temporarily rate-limited. Please wait a moment and try again.' })
        return
      }
      case 'auth-error': {
        console.error('[AI Route] Gemini authentication or configuration error')
        res.status(502).json({
          error: 'AI service configuration error. Please check server settings or use offline demo mode.',
        })
        return
      }
      case 'invalid-output': {
        console.warn('[AI Route] Gemini output failed schema validation — using demo fallback')
        const ideas = getDemoIdeas(data)
        res.json({ ideas, source: 'demo', disclaimer: DISCLAIMER })
        return
      }
      case 'transient': {
        console.warn('[AI Route] Gemini transient failure after retries — using demo fallback')
        const ideas = getDemoIdeas(data)
        res.json({ ideas, source: 'demo', disclaimer: DISCLAIMER })
        return
      }
    }
  } catch (err) {
    next(err)
  }
})

export default router
